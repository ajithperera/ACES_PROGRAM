










      SUBROUTINE READ_ACT1AMPS(IUNIT,ILIST,ISPIN,MODE,ACTISFULL)

      IMPLICIT INTEGER (A-Z)
      LOGICAL ACTISFULL
      CHARACTER*4 MODE


      PARAMETER (MAX_ACT_SPACE = 50)



      DOUBLE PRECISION T1AS(MAX_ACT_SPACE**2), T2AS(MAX_ACT_SPACE**4)
C
      DIMENSION I1(MAX_ACT_SPACE**2), A1(MAX_ACT_SPACE**2),
     &          I2(MAX_ACT_SPACE**4), A2(MAX_ACT_SPACE**4),
     &          J2(MAX_ACT_SPACE**4), B2(MAX_ACT_SPACE**4)
      DIMENSION IR1(MAX_ACT_SPACE**2), AR1(MAX_ACT_SPACE**2),
     &          IR2(MAX_ACT_SPACE**4), JR2(MAX_ACT_SPACE**4),
     &          AR2(MAX_ACT_SPACE**4), BR2(MAX_ACT_SPACE**4)
C
      COMMON /T1ASPACE/ I1, IR1, A1, AR1, T1AS, NT1SIZE
      COMMON /T2ASPACE/ I2, IR2, J2, JR2, A2, AR2, B2, BR2, T2AS,
     &                  NT2SIZE
    

C
      COMMON /SYMINF/ NSTART, NIRREP, IRREPS(255,2), DIRPRD(8,8)
      COMMON /OFF4ASPACE/ IACT_POP_OFF(8), IACT_VRT_OFF(8)
      COMMON /SYMPOP/ IRPDPD(8,22),ISYTYP(2,500),ID(18)

CSSS      READ(IUNIT, "(8I4)") (IACT_POP_OFF(IRREP), IRREP=1, NIRREP)
CSSS      READ(IUNIT, "(8I4)") (IACT_VRT_OFF(IRREP), IRREP=1, NIRREP)
C
      READ(IUNIT,*) NT1SIZE

      DO I = 1, NT1SIZE
         READ(IUNIT,9) I1(I),IR1(I),A1(I),AR1(I),T1AS(I)
      ENDDO
    
 9    FORMAT(3X,I4,3X,I1,3X,I4,3X, I1, 3X, F15.12)

C
      NT1_INT_SIZ=IRPDPD(1,8+ISPIN)
      ACTISFULL = .FALSE.
C
      IF (NT1_INT_SIZ .EQ. NT1SIZE) THEN
          ACTISFULL = .TRUE.
          IF(MODE .EQ. "AMPS") CALL PUTLST(T1AS,1,1,1,ISPIN,ILIST)
          IF(MODE .EQ. "RESD") CALL PUTLST(T1AS,1,1,1,ISPIN+2,ILIST)
      ENDIF 

C
      RETURN
      END
