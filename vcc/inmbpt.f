
     
      SUBROUTINE INMBPT(ICORE,MAXCOR,IUHF)
C
C INITIALIZES T2 INCREMENT AREA FOR MBPT CALCULATIONS.
C 
CEND
      IMPLICIT INTEGER (A-Z)
      COMMON /MACHSP/ IINTLN,IFLTLN,IINTFP,IALONE,IBITWD
      COMMON /INFO/ NOCCO(2),NVRTO(2)
      COMMON /SYMPOP/ IRPDPD(8,22),ISYTYP(2,500),ID(18)
C
      IMODE=0
      WRITE(6,*) '@INMBPT-DEBUG: entered, IUHF=',IUHF
      DO 10 ISPIN=1,1+IUHF
       WRITE(6,*) '@INMBPT-DEBUG: before ISPIN=',ISPIN,
     &   ' ISYTYP(1,43+ISPIN)=',ISYTYP(1,43+ISPIN),
     &   ' ISYTYP(2,43+ISPIN)=',ISYTYP(2,43+ISPIN)
       CALL INIPCK(1,ISYTYP(1,43+ISPIN),ISYTYP(2,43+ISPIN),
     &             60+ISPIN,IMODE,0,1)
       WRITE(6,*) '@INMBPT-DEBUG: after ISPIN=',ISPIN,
     &   ' ISYTYP(1,60+ISPIN)=',ISYTYP(1,60+ISPIN),
     &   ' ISYTYP(2,60+ISPIN)=',ISYTYP(2,60+ISPIN)
       CALL ZERSYM(ICORE,60+ISPIN)
10    CONTINUE
      WRITE(6,*) '@INMBPT-DEBUG: before list63, ISYTYP(1,46)=',
     &   ISYTYP(1,46),' ISYTYP(2,46)=',ISYTYP(2,46)
      CALL INIPCK(1,ISYTYP(1,46),ISYTYP(2,46),63,IMODE,0,1)
      WRITE(6,*) '@INMBPT-DEBUG: after list63, ISYTYP(1,63)=',
     &   ISYTYP(1,63),' ISYTYP(2,63)=',ISYTYP(2,63)
      CALL ZERSYM(ICORE,63)
C
C CREATE RING INCREMENT AREA
C
      CALL INIPCK(1,9,10,42,IMODE,0,1)
      CALL INIPCK(1,11,12,43,IMODE,0,1)
      CALL INIPCK(1,10,10,41,IMODE,0,1)
      IF(IUHF.NE.0)THEN
       CALL INIPCK(1,9,9,40,IMODE,0,1)
      ENDIF
      RETURN
      END
