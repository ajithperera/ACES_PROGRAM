
C RETURNS THE RANGE-SEPARATION PARAMETER OMEGA (BOHR**-1) OF THE
C LONG-RANGE INTEGRALS ERF(OMEGA*R12)/R12, READ FROM THE *INTGRT
C NAMELIST. OMEGA IS ZERO (NO LONG-RANGE INTEGRALS) UNLESS FUNC OR
C KSPOT NAMES A RANGE-SEPARATED HYBRID OR RS_OMEGA IS GIVEN.
C
C    FUNC=HYBRID OR KSPOT=HYBRID : OMEGA DEFAULTS TO THE ONE OF THE
C                                  HYBRID (HYBPARM), FUNC FIRST
C    RS_OMEGA=X                  : OMEGA=X
C
C THE SAME RULES ARE APPLIED BY INITINTGRT, SO THE INTEGRAL PROGRAM
C (VMOL, OR XERDINTS WITH INTEGRALS=ERD), VSCF AND INTGRT AGREE ON
C OMEGA.

      SUBROUTINE RSOMEGA(OMEGA)
      IMPLICIT NONE
#include <aces.h>
#include <dftfunc.com>
      DOUBLE PRECISION OMEGA

      CHARACTER*80 SZFUNC, SZPOT
      CHARACTER*20 ELE
      CHARACTER*10 ABB
      CHARACTER*50 NAM
      INTEGER IERR, IPTR, I, J
      LOGICAL STREQ
      DOUBLE PRECISION DEF, W, CX(FUN_NUM_EXCH), CC(FUN_NUM_CORR)

      CALL NL_INIT('INTGRT',IERR,.FALSE.)
      CALL NL_STR('func','none',SZFUNC)
      CALL NL_STR('kspot','hf',SZPOT)

      DEF=0.D0
      DO J=1,2
         IPTR=0
         IF (J.EQ.1) CALL LIST_NEXT_ELE(SZFUNC,IPTR,ELE,IERR)
         IF (J.EQ.2) CALL LIST_NEXT_ELE(SZPOT,IPTR,ELE,IERR)
         IF (IERR.EQ.0 .AND. DEF.EQ.0.D0) THEN
            DO I=1,FUN_NUM_HYB
               CALL HYBPARM(I,ABB,NAM,CX,CC,W)
               IF (STREQ(ELE,ABB,.TRUE.)) DEF=W
            END DO
         END IF
      END DO

      CALL NL_REAL('rs_omega',DEF,OMEGA)
C NO NL_TERM: THE REST OF *INTGRT IS LEFT FOR INITINTGRT TO READ AND
C NL_TERM WOULD REJECT IT AS UNUSED.

      IF (OMEGA.LT.0.D0) THEN
         WRITE(6,1000) OMEGA
 1000    FORMAT(T3,'@RSOMEGA-F, RS_OMEGA must not be negative: ',F12.6)
         CALL ERREX
      END IF

      RETURN
      END

