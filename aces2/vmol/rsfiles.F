
C CLOSES THE INTEGRAL FILES OPENED BY READIN (IIII, IJIJ, IIJJ, IJKL)
C AND OPENS THE LONG-RANGE FILES (IIIILR, IJIJLR, IIJJLR, IJKLLR) ON
C THE SAME UNITS, SO A SECOND PASS THROUGH TWOEL WRITES THE LONG-RANGE
C INTEGRALS. WHICH FILES EXIST DEPENDS ON NSYMOP AS IN READIN.

      SUBROUTINE RSFILES(NSYMOP)
      IMPLICIT NONE
      INTEGER NSYMOP

      CHARACTER*8 SZNAME(4)
      CHARACTER*80 FNAME
      INTEGER IUNIT(4), NFILE, I, ILENGTH
      DATA SZNAME /'IIIILR  ','IJIJLR  ','IIJJLR  ','IJKLLR  '/
      DATA IUNIT /2,81,82,83/

      IF (NSYMOP.EQ.0) THEN
         NFILE=1
      ELSE IF (NSYMOP.EQ.1) THEN
         NFILE=3
      ELSE
         NFILE=4
      END IF

      DO I=1,NFILE
         CLOSE(UNIT=IUNIT(I),STATUS='KEEP')
         CALL GFNAME(SZNAME(I),FNAME,ILENGTH)
         OPEN(UNIT=IUNIT(I),FILE=FNAME(1:ILENGTH),FORM='UNFORMATTED',
     &        STATUS='UNKNOWN',ACCESS='SEQUENTIAL')
      END DO

      RETURN
      END

