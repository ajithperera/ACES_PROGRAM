
C TURNS THE COULOMB OPERATOR 1/R12 INTO ERF(OMEGA*R12)/R12 FOR A BATCH
C OF PRIMITIVE QUARTETS.
C
C WITH RHO=P*Q/(P+Q) THE ATTENUATED INTEGRALS ARE THE ORDINARY ONES
C WITH RHO REPLACED BY RHO*W2/(RHO+W2), W2=OMEGA**2, EVERYWHERE (THE
C BOYS FUNCTION ARGUMENT AND THE (-2*RHO)**N FACTORS OF ITS
C DERIVATIVES), AND THE PREFACTOR SCALED BY SQRT(W2/(RHO+W2)).
C
C RHO  : P*Q/(P+Q) ON INPUT, ITS ATTENUATED VALUE ON OUTPUT
C ROOT : THE PREFACTOR, SCALED ON OUTPUT
C N    : THE NUMBER OF QUARTETS

      SUBROUTINE RSATTN(RHO,ROOT,N,OMEGA)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION RHO(N),ROOT(N)
      W2=OMEGA*OMEGA
      DO 10 I=1,N
      FAC=W2/(RHO(I)+W2)
      ROOT(I)=ROOT(I)*SQRT(FAC)
      RHO(I)=RHO(I)*FAC
   10 CONTINUE
      RETURN
      END

