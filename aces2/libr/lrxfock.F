
c THIS ROUTINE ADDS THE LONG-RANGE EXCHANGE OF RANGE-SEPARATED HYBRIDS
c TO A FOCK MATRIX, USING THE LONG-RANGE AO INTEGRALS
c ERF(OMEGA*R12)/R12 THAT VMOL WRITES TO IIIILR AND IJIJLR:
c
c    F(I,K) = F(I,K) + FAC D(J,L) (IJ|KL)LR
c    F(J,L) = F(J,L) + FAC D(I,K) (IJ|KL)LR
c    F(I,L) = F(I,L) + FAC D(J,K) (IJ|KL)LR
c    F(J,K) = F(J,K) + FAC D(I,L) (IJ|KL)LR
c
c WITH THE SAME CONVENTIONS AS THE EXCHANGE TERMS OF MKRHFF/MKUHFF
c (FAC=-1/4 TIMES THE COEFFICIENT FOR RHF, -1/2 TIMES IT FOR EACH SPIN
c OF UHF). IIJJLR AND IJKLLR GIVE NO EXCHANGE AND ARE NOT READ.
c
c   F    - SYMMETRY BLOCKED FOCK MATRIX (ONE SPIN)
c   D    - SYMMETRY BLOCKED DENSITY MATRIX (THE SAME SPIN)
c   BUF  - BUFFER OF SIZE ILNBUF*IINTFP FOR INTEGRALS
c   IBUF - BUFFER OF SIZE ILNBUF FOR INDICES
c   IMAP - SYMMETRY VECTOR (FULL ARRAY -> SYMMETRY BLOCKED), AS SET UP
c          BY MKRHFF/MKUHFF
c   LUINT - UNIT NUMBER FOR INTEGRAL FILE

      SUBROUTINE LRXFOCK(F,D,BUF,IBUF,NTOTAL,NBAST,IMAP,ILNBUF,LUINT,
     &                   FAC)
      IMPLICIT NONE
      INTEGER NTOTAL, NBAST, ILNBUF, LUINT
      DOUBLE PRECISION F(NTOTAL), D(NTOTAL), BUF(ILNBUF), FAC
      INTEGER IBUF(ILNBUF), IMAP(NBAST,NBAST)

      DOUBLE PRECISION X
      INTEGER IJ, IK, IL, JK, JL, KL, INDI, INDJ, INDK, INDL
      INTEGER ILENGTH, NUT
      CHARACTER*80 FNAME

#include "machsp.com"
#include "syminf.com"

      DOUBLE PRECISION HALF
      PARAMETER (HALF=0.5D0)

      INTEGER IAND,ISHFT
      INTEGER I, J, INT, IUPKI, IUPKJ, IUPKK, IUPKL, INDX
      IUPKI(INT)=IAND(INT,IALONE)
      IUPKJ(INT)=IAND(ISHFT(INT,-IBITWD),IALONE)
      IUPKK(INT)=IAND(ISHFT(INT,-2*IBITWD),IALONE)
      IUPKL(INT)=IAND(ISHFT(INT,-3*IBITWD),IALONE)
      INDX(I,J)=J+(I*(I-1))/2

c IIIILR
      CALL GFNAME('IIIILR  ',FNAME,ILENGTH)
      OPEN(UNIT=LUINT,FILE=FNAME(1:ILENGTH),FORM='UNFORMATTED',
     &     STATUS='OLD',ACCESS='SEQUENTIAL')
      CALL LOCATE(LUINT,'TWOELSUP')
 1    CONTINUE
         READ(LUINT) BUF, IBUF, NUT
         DO INT=1,NUT
            X=BUF(INT)
            INDI=IUPKI(IBUF(INT))
            INDJ=IUPKJ(IBUF(INT))
            INDK=IUPKK(IBUF(INT))
            INDL=IUPKL(IBUF(INT))
            IJ=IMAP(INDJ,INDI)
            KL=IMAP(INDL,INDK)
            IK=IMAP(INDK,INDI)
            JL=IMAP(INDL,INDJ)
            IL=IMAP(INDL,INDI)
            JK=IMAP(INDJ,INDK)
            IF (INDI.EQ.INDJ) X=X*HALF
            IF (INDK.EQ.INDL) X=X*HALF
            IF (IJ.EQ.KL)     X=X*HALF
            F(IK)=F(IK)+FAC*D(JL)*X
            F(JL)=F(JL)+FAC*D(IK)*X
            F(IL)=F(IL)+FAC*D(JK)*X
            F(JK)=F(JK)+FAC*D(IL)*X
         END DO
      IF (NUT.NE.-1) GOTO 1
      CLOSE(UNIT=LUINT,STATUS='KEEP')

c IJIJLR
      IF (NIRREP.GT.1) THEN
         CALL GFNAME('IJIJLR  ',FNAME,ILENGTH)
         OPEN(UNIT=LUINT,FILE=FNAME(1:ILENGTH),FORM='UNFORMATTED',
     &        STATUS='OLD',ACCESS='SEQUENTIAL')
         CALL LOCATE(LUINT,'TWOELSUP')
 201     CONTINUE
            READ(LUINT) BUF, IBUF, NUT
            DO INT=1,NUT
               X=BUF(INT)
               INDI=IUPKI(IBUF(INT))
               INDJ=IUPKJ(IBUF(INT))
               INDK=IUPKK(IBUF(INT))
               INDL=IUPKL(IBUF(INT))
               IJ=INDX(MAX(INDJ,INDI),MIN(INDJ,INDI))
               KL=INDX(MAX(INDL,INDK),MIN(INDL,INDK))
               IK=IMAP(INDK,INDI)
               JL=IMAP(INDL,INDJ)
               IF (IJ.EQ.KL) X=X*HALF
               F(IK)=F(IK)+FAC*D(JL)*X
               F(JL)=F(JL)+FAC*D(IK)*X
            END DO
         IF (NUT.NE.-1) GOTO 201
         CLOSE(UNIT=LUINT,STATUS='KEEP')
      END IF

      RETURN
      END
