










      SUBROUTINE VCCEH_XPROP(ICORE, MAXCOR, NSIZEC, NUMPERT, IRREPX)
C
C DEBUG CROSS-CHECK: PRINTS VCCEH'S OWN SECOND-ORDER PROPERTY MATRIX
C X(I,J) = <M(L)_I | T(1)_J> (LISTS 374 AND 373, UHF), THE QUANTITY
C THAT TR(D(1)_J H_I) MUST REPRODUCE. NO FACTOR OF 2 APPLIED.
C
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      DOUBLE PRECISION ICORE(*)
C
      I000 = 1
      I010 = I000 + NSIZEC
      IF (I010 + NSIZEC .GT. MAXCOR) RETURN
      WRITE(6, "(a,I2)") " vcceh <374_I|373_J> for irrep ", IRREPX
      DO I = 1, NUMPERT
         CALL GETLST(ICORE(I000), I, 1, 1, IRREPX, 374)
         DO J = 1, NUMPERT
            CALL GETLST(ICORE(I010), J, 1, 1, IRREPX, 373)
            X = SDOT(NSIZEC, ICORE(I000), 1, ICORE(I010), 1)
            WRITE(6, "(1x,2I4,F20.12)") I, J, X
         ENDDO
      ENDDO
C
      RETURN
      END
