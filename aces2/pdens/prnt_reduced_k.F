      SUBROUTINE PRNT_REDUCED_K(SPINJJ, ICHARGE, GTAB, LABEL, NNUCL,
     &                          TERM)
C
C PRINTS THE REDUCED COUPLING K(AB) = 4*PI**2*J(AB)/(H*G(A)*G(B)),
C THE NUCLEUS-INDEPENDENT PART OF J, IN UNITS OF 10**19 T**2/J
C (= 10**19 N A**-2 M**-3). G = GYROMAGNETIC RATIO (RAD/(S T)).
C SPINJJ HOLDS J IN HZ (LOWER TRIANGLE, AS FILLED BY THE CALLER).
C
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      CHARACTER*6 LABEL(*)
      CHARACTER*(*) TERM
      DIMENSION SPINJJ(100, 100), GTAB(*), ICHARGE(*), XK(100, 100)
C
      PARAMETER (PLANCK = 6.62607015D-34)
C
      PI   = 4.0D0*ATAN(1.0D0)
      SCAL = 4.0D0*PI*PI/PLANCK*1.0D-19
C
      CALL ZERO(XK, 100*100)
      DO I = 1, NNUCL
         GI = GTAB(ICHARGE(I))
         DO J = 1, I
            GJ = GTAB(ICHARGE(J))
            XK(I, J) = SPINJJ(I, J)*SCAL/(GI*GJ)
         ENDDO
      ENDDO
C
      CALL HEADER(TERM//' reduced coupling K (10**19 T**2/J)', -1, 6)
      CALL PRNTLO(6, XK, LABEL, NNUCL, NNUCL, 100, 100)
C
      RETURN
      END
