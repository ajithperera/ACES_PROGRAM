      SUBROUTINE PDDUMP(TAG, IDX, N, A)
C
C WRITES ONE RECORD TO THE PDENS ANALYSIS FILE (pdens_dump.bin, STREAM
C ACCESS): 8-CHARACTER TAG, INTEGER INDEX, INTEGER LENGTH, THEN LENGTH
C DOUBLES. THE FILE CARRIES THE AO RESPONSE DENSITIES, THE PROPERTY
C INTEGRALS (INDEXED LIKE THE ROWS OF THE PROPERTY TENSOR) AND THE BASIS
C INFORMATION, SO THAT THE DECOMPOSITIONS CAN BE DONE OUTSIDE PDENS.
C
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      CHARACTER*8 TAG
      LOGICAL LINTDMP
      DIMENSION A(N)
      COMMON /PDDMP/ IUDMP, LINTDMP
C
      IF (IUDMP .LE. 0) RETURN
      WRITE(IUDMP) TAG, IDX, N, (A(I), I = 1, N)
C
      RETURN
      END
C
      SUBROUTINE PDDUMPI(TAG, IDX, N, IA)
C
C INTEGER VERSION OF PDDUMP (THE INTEGERS ARE WRITTEN AS DOUBLES).
C
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      CHARACTER*8 TAG
      LOGICAL LINTDMP
      DIMENSION IA(N)
      COMMON /PDDMP/ IUDMP, LINTDMP
C
      IF (IUDMP .LE. 0) RETURN
      WRITE(IUDMP) TAG, IDX, N, (DBLE(IA(I)), I = 1, N)
C
      RETURN
      END
