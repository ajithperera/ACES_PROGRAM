#!/usr/bin/env python3
"""Generate the table of ACES III default jobflows.

Reads aces3/src/aces/aces_sial/default_jobflows (the SIAL programs run for
each job type when the ZMAT names none) and the jobflow names that
aces3/src/main/write_default_sial_programs.f can request, and writes a
Markdown table plus a list of names the code requests but the file lacks.

Usage: gen_jobflows.py ACES3_DIR OUTPUT_MD
"""
import os
import re
import sys


def main(aces3, out_md):
    flows, order, cur = {}, [], None
    with open(os.path.join(aces3, "src/aces/aces_sial/default_jobflows")) as f:
        for line in f:
            s = line.strip()
            if s.startswith("ENDJOBFLOW"):
                cur = None
            elif s.startswith("JOBFLOW"):
                cur = s.split()[1]
                flows[cur] = []
                order.append(cur)
            elif cur and s and not s.startswith("#"):
                flows[cur].append(s)
    with open(os.path.join(aces3, "src/main/write_default_sial_programs.f")) as f:
        src = f.read()
    requested = set(re.findall(r"jobflow\s*=\s*'([A-Z0-9_]+)'", src)) - {"UNDEFINED"}
    missing = sorted(requested - set(flows))

    out = ["<!-- GENERATED by docs/tools/gen_jobflows.py -- do not edit. -->\n",
           "| Jobflow | SIAL programs, in order |", "|---|---|"]
    for name in order:
        progs = ", ".join(f"`{p}`" for p in flows[name])
        out.append(f"| `{name}` | {progs} |")
    if missing:
        out.append("\n```{warning}\n`xaces3` can select these jobflows, but "
                   "`default_jobflows` does not define them, so such jobs "
                   "stop with \"Cannot find jobflow\": " +
                   ", ".join(f"`{m}`" for m in missing) +
                   ". Give the SIAL programs explicitly for these cases.\n```")
    aguess = [n for n in order if any("aguess" in p for p in flows[n])]
    if aguess:
        out.append("\n```{note}\nThe jobflows " +
                   ", ".join(f"`{n}`" for n in aguess) +
                   " still start from the `scf_*aguess` SCF programs. The "
                   "test suite uses `scf_rhf.sio` and `scf_uhf.sio` instead.\n```")
    with open(out_md, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"gen_jobflows: {len(order)} jobflows, {len(missing)} requested but missing")


if __name__ == "__main__":
    main(*sys.argv[1:3])
