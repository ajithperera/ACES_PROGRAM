#!/usr/bin/env python3
"""Generate the JOBARC record catalog from the ACES II sources.

Scans every Fortran source under aces2/ for PUTREC and GETREC calls on the
JOBARC file whose record name is a literal, and lists for each record the
source directories that write and read it.  Descriptions come from the
hand-maintained docs/programmer/jobarc_notes.md ('## NAME' headings).

Usage: gen_jobarc.py ACES2_DIR NOTES_MD OUTPUT_MD
"""
import collections
import os
import re
import sys

CALL = re.compile(r"\b(PUTREC|GETREC)\s*\(\s*[^,()]+,\s*'JOBARC'\s*,\s*('([^']*)'|[A-Za-z])",
                  re.I)
SKIP = ("/old", ".skip", "/CVS", "/tests", "/Test")


def scan(aces2):
    writers = collections.defaultdict(set)
    readers = collections.defaultdict(set)
    computed = 0
    for root, dirs, files in os.walk(aces2):
        dirs.sort()
        if any(s in root for s in SKIP):
            continue
        names = set(files)
        for f in files:
            # .f files are preprocessed copies of .F files; scan them only alone
            if not (f.endswith(".F") or (f.endswith(".f") and f[:-2] + ".F" not in names)):
                continue
            with open(os.path.join(root, f), errors="replace") as fh:
                text = fh.read()
            text = re.sub(r"\n     [^ \n]", "", text)  # join continuation lines
            where = os.path.relpath(root, aces2).split(os.sep)[0]
            for m in CALL.finditer(text):
                if m.group(3) is None:
                    computed += m.group(1).upper() == "PUTREC"
                    continue
                name = m.group(3).strip().upper()
                if not name:
                    continue
                table = writers if m.group(1).upper() == "PUTREC" else readers
                table[name].add(where)
    return writers, readers, computed


def parse_notes(path):
    notes, key, buf = {}, None, []
    with open(path) as f:
        for line in f:
            if line.startswith("## "):
                if key:
                    notes[key] = " ".join(buf).strip()
                key, buf = line[3:].strip().upper(), []
            elif key is not None and not line.startswith("<!--"):
                buf.append(line.strip())
    if key:
        notes[key] = " ".join(buf).strip()
    return notes


def cell(dirs):
    return ", ".join(f"`{d}`" for d in sorted(dirs)) if dirs else "–"


def main(aces2, notes_md, out_md):
    writers, readers, computed = scan(aces2)
    notes = parse_notes(notes_md)
    names = sorted(set(writers) | set(readers))
    only_read = [n for n in names if n not in writers]
    stale = sorted(n for n in notes if n not in writers and n not in readers)

    out = []
    w = out.append
    w("<!-- GENERATED by docs/tools/gen_jobarc.py -- do not edit. -->")
    w("<!-- Edit docs/programmer/jobarc_notes.md for descriptions. -->\n")
    w("(jobarc-catalog)=")
    w("# JOBARC record catalog\n")
    w("Every record name that ACES II writes to or reads from `JOBARC` "
      "with a literal name in a `PUTREC` or `GETREC` call, and the source "
      "directories that do so. The list is regenerated from the code "
      "every time the manual is built.\n")
    w(f"There are **{len(names)}** records: {len(writers)} are written and "
      f"{len(names) - len(writers)} are only read. Most of the records that "
      f"are only read are written under a name built at run time: "
      f"{computed} `PUTREC` calls compute the record name, and this scan "
      "cannot see those names. Descriptions exist for "
      f"{sum(1 for n in names if n in notes)} records so far; add more in "
      "`docs/programmer/jobarc_notes.md`.\n")
    w("Abbreviations in the descriptions: NAO, number of AO basis functions; "
      "NSO, number of symmetry-adapted functions; NMO, number of MOs; "
      "NATOMS, number of Z-matrix centers; NIRREP, number of irreps of the "
      "computational point group; NOrbits, number of symmetry-unique "
      "centers.\n")
    w("| Record | Written in | Read in | Description |")
    w("|---|---|---|---|")
    for n in names:
        desc = notes.get(n, "")
        w(f"| `{n}` | {cell(writers.get(n))} | {cell(readers.get(n))} | {desc} |")
    if stale:
        w("\n## Described but not found in the code\n")
        w("These have descriptions in `jobarc_notes.md` but no literal "
          "`PUTREC` or `GETREC` uses them: " +
          ", ".join(f"`{n}`" for n in stale) + ".\n")
    with open(out_md, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"gen_jobarc: {len(names)} records, {len(only_read)} only read, "
          f"{computed} computed-name PUTRECs, {len(stale)} stale notes")


if __name__ == "__main__":
    main(*sys.argv[1:4])
